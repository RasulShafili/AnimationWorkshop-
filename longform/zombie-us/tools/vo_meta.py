#!/usr/bin/env python3
"""Read vo/<prefix>*.wav → src/vo_<prefix>.ts with each line's length (frames @30fps) and a per-frame loudness
envelope (0..1) for lip-sync. Also normalises every line to -18 LUFS-ish peak and copies nothing else.
  python3 tools/vo_meta.py c1"""
import glob, json, os, subprocess, sys
import numpy as np
pre = sys.argv[1]
out = {}
for f in sorted(g for g in glob.glob(f"vo/{pre}_*.wav") if not g.endswith(".orig.wav")):
    x = np.frombuffer(subprocess.run(["ffmpeg", "-v", "quiet", "-i", f, "-ac", "1", "-ar", "24000", "-f", "f32le", "-"], capture_output=True).stdout, np.float32)
    # trim leading/trailing silence
    a = np.abs(x); thr = a.max() * 0.02; nz = np.where(a > thr)[0]
    x = x[max(0, nz[0] - 600): nz[-1] + 2400] if len(nz) else x
    hop = 24000 // 30
    env = np.array([np.sqrt(np.mean(x[i:i + hop] ** 2)) for i in range(0, len(x), hop)])
    env = np.clip(env / (np.percentile(env, 95) + 1e-6), 0, 1)
    env = np.convolve(env, [0.25, 0.5, 0.25], mode="same")
    name = os.path.basename(f)[:-4]
    out[name] = {"dur": len(env), "env": [round(float(v), 2) for v in env]}
    np.save(f"vo/{name}.npy", x)  # trimmed audio for the mixer
ts = "// generated by tools/vo_meta.py — line lengths (frames) and lip-sync envelopes\n"
ts += f"export const VO_{pre.upper()}: Record<string, {{ dur: number; env: number[] }}> = {json.dumps(out)};\n"
ts += "export const talkAt = (vo: { env: number[] } | undefined, f: number, start: number) => { if (!vo) return 0; const i = Math.floor(f - start); return i >= 0 && i < vo.env.length ? vo.env[i] : 0; };\n"
open(f"src/vo_{pre}.ts", "w").write(ts)
for k, v in out.items(): print(f"{k:14s} {v['dur']:4d} f  {v['dur'] / 30:.2f}s")
