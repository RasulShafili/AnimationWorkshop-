function toUpperAz(str: string): string {
  return str
    .replace(/ə/g, "Ə")
    .replace(/ı/g, "I")
    .replace(/i/g, "İ")
    .replace(/ö/g, "Ö")
    .replace(/ü/g, "Ü")
    .replace(/ş/g, "Ş")
    .replace(/ç/g, "Ç")
    .replace(/ğ/g, "Ğ")
    .toUpperCase();
}

interface PixelTextAzProps {
  text: string;
  pixelSize?: number;
  color?: string;
  shadowColor?: string;
  outlineColor?: string;
  letterSpacingPx?: number;
}

export const PixelTextAz: React.FC<PixelTextAzProps> = ({
  text,
  pixelSize = 4,
  color = "#FFFFFF",
  shadowColor,
  outlineColor,
  letterSpacingPx = 1,
}) => {
  const upper = toUpperAz(text);
  const chars = Array.from(upper);
  const charCols = 5;
  const charRows = 8;
  const stepCols = charCols + letterSpacingPx;
  const totalCols = Math.max(1, chars.length * stepCols - letterSpacingPx + 2);
  const totalRows = charRows + 2;

  const rects: React.ReactNode[] = [];

  // Helper to check if a pixel is active in any character
  const isSet = (gx: number, gy: number): boolean => {
    const cIdx = Math.floor((gx - 1) / stepCols);
    const localX = (gx - 1) - cIdx * stepCols;
    const localY = gy - 1;
    if (
      cIdx < 0 ||
      cIdx >= chars.length ||
      localX < 0 ||
      localX >= charCols ||
      localY < 0 ||
      localY >= charRows
    ) {
      return false;
    }
    const g = GLYPHS_5X8[chars[cIdx]] || GLYPHS_5X8[" "];
    return g[localY]?.[localX] === "#";
  };

  // 1. Optional Outline + Drop Shadow Pass
  if (outlineColor || shadowColor) {
    for (let gy = 0; gy < totalRows; gy++) {
      for (let gx = 0; gx < totalCols; gx++) {
        if (isSet(gx, gy)) continue;
        // Check 8-neighbors for outline
        let near = false;
        if (outlineColor) {
          for (let dy = -1; dy <= 1 && !near; dy++) {
            for (let dx = -1; dx <= 1 && !near; dx++) {
              if (isSet(gx + dx, gy + dy)) near = true;
            }
          }
        }
        const isShadow = shadowColor && (isSet(gx - 1, gy - 1) || isSet(gx - 1, gy) || isSet(gx, gy - 1));
        if (near || isShadow) {
          rects.push(
            <rect
              key={`bg-${gx}-${gy}`}
              x={gx * pixelSize}
              y={gy * pixelSize}
              width={pixelSize}
              height={pixelSize}
              fill={outlineColor || shadowColor}
            />
          );
        }
      }
    }
  }

  // 2. Main Foreground Glyph Pixels Pass
  for (let gy = 1; gy < totalRows - 1; gy++) {
    for (let gx = 1; gx < totalCols - 1; gx++) {
      if (isSet(gx, gy)) {
        rects.push(
          <rect
            key={`fg-${gx}-${gy}`}
            x={gx * pixelSize}
            y={gy * pixelSize}
            width={pixelSize}
            height={pixelSize}
            fill={color}
          />
        );
      }
    }
  }

  return (
    <svg
      width={totalCols * pixelSize}
      height={totalRows * pixelSize}
      viewBox={`0 0 ${totalCols * pixelSize} ${totalRows * pixelSize}`}
      shapeRendering="crispEdges"
      style={{ display: "block", overflow: "visible" }}
    >
      {rects}
    </svg>
  );
};
